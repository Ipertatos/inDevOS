#!/usr/bin/env python3
"""libcss: parse and compute CSS Grid properties (grid-template-columns/rows,
grid-auto-*, grid-column/row-*, grid-auto-flow, gap/row-gap,
justify-items/self ...). Parsers in grid/libcss_parse_grid.c, cascade/compute
in grid/libcss_select_grid.c (copied as grid.c), table/plumbing via the diff.
The diff edits select_config.py; the select autogenerated_{computed,propget,
propset}.h headers are then regenerated with libcss's own select_generator.py.

Usage: libcss_grid.py <path/to/netsurf-all-3.11>   (idempotent; applies libcss_grid.diff)"""
import os
import shutil
import subprocess
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nsdiff

if len(sys.argv) != 2:
    sys.exit(__doc__)
nsdiff.apply('libcss_grid', sys.argv[1], [
    ('grid/libcss_parse_grid.c', 'libcss/src/parse/properties/grid.c'),
    ('grid/libcss_select_grid.c', 'libcss/src/select/properties/grid.c'),
])

# libcss does not regenerate these at build time: run its generator now.
sel = os.path.join(sys.argv[1], 'libcss', 'src', 'select')
subprocess.run([sys.executable, 'select_generator.py'], cwd=sel, check=True)
shutil.rmtree(os.path.join(sel, '__pycache__'), ignore_errors=True)
print('libcss_grid: regenerated select autogenerated_*.h')
