const int kernel_symbols_count = sizeof(kernel_symbols) / sizeof(kernel_symbols[0]);

const char* lookup_symbol(uint64_t addr) {
    const char* name = "unknown";
    for (int i = 0; i < kernel_symbols_count; ++i) {
        if (addr < kernel_symbols[i].addr)
            break;
        name = kernel_symbols[i].name;
    }
    return name;
}
